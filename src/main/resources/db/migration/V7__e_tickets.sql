ALTER TABLE users DROP CONSTRAINT chk_users_role;
ALTER TABLE users ADD CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN', 'SCANNER'));

-- ---------------------------------------------------------------------------
-- ticket_checkins — one row per successfully scanned seat (replay guard)
-- ---------------------------------------------------------------------------
CREATE TABLE ticket_checkins (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     BIGINT       NOT NULL,
    seat_id        BIGINT       NOT NULL,
    checked_in_at  TIMESTAMPTZ  NOT NULL,
    checked_in_by  VARCHAR(255) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_ticket_checkins_seat UNIQUE (seat_id),
    CONSTRAINT fk_ticket_checkins_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT fk_ticket_checkins_seat FOREIGN KEY (seat_id) REFERENCES seats (id) ON DELETE CASCADE
);
CREATE INDEX idx_ticket_checkins_booking ON ticket_checkins (booking_id);
