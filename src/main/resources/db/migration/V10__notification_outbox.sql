-- ============================================================================
-- V10 — Email notifications: a transactional outbox
-- ============================================================================
-- A row is written in the SAME transaction as the booking change it announces
-- (confirm, cancel, refund), so an email can never be promised for a change that
-- rolled back, nor lost for one that committed. A background dispatcher sends
-- due rows over SMTP and retries failures with exponential backoff.

CREATE TABLE notifications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(32)  NOT NULL,
    booking_id       BIGINT       NOT NULL,
    recipient        VARCHAR(255) NOT NULL,
    -- One email per (type, booking): a repeated confirm path or reminder sweep is a no-op.
    dedupe_key       VARCHAR(100) NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    attempts         INTEGER      NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMPTZ  NOT NULL,
    -- While SENDING, the claim expires at lease_until so a crashed sender's rows are retried.
    lease_until      TIMESTAMPTZ,
    last_error       VARCHAR(500),
    sent_at          TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_notifications_dedupe UNIQUE (dedupe_key),
    CONSTRAINT fk_notifications_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT chk_notifications_type CHECK (type IN
        ('BOOKING_CONFIRMED', 'PAYMENT_RECEIPT', 'BOOKING_CANCELLED', 'PAYMENT_REFUNDED', 'EVENT_REMINDER')),
    CONSTRAINT chk_notifications_status CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED')),
    CONSTRAINT chk_notifications_attempts CHECK (attempts >= 0)
);

-- The dispatcher's claim query: due PENDING rows, and SENDING rows whose lease lapsed.
CREATE INDEX idx_notifications_due ON notifications (status, next_attempt_at);
CREATE INDEX idx_notifications_booking ON notifications (booking_id);
